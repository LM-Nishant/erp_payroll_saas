/* --------------------------------- Generation job --------------------------------------- */

const ddmmyyyy = (d: Date) =>
  `${String(d.getUTCDate()).padStart(2, '0')}/${String(d.getUTCMonth() + 1).padStart(2, '0')}/${d.getUTCFullYear()}`;

async function employeeProfiles(employeeIds: string[]) {
  const employees = await db().employee.findMany({
    where: { id: { in: employeeIds } },
    select: { id: true, designationId: true, dateOfJoining: true },
  });
  const designationIds = employees.map((e) => e.designationId).filter((d): d is string => !!d);
  const designations = await db().designation.findMany({
    where: { id: { in: designationIds } },
    select: { id: true, name: true },
  });
  const names = new Map(designations.map((d) => [d.id, d.name]));
  return new Map(
    employees.map((e) => [
      e.id,
      {
        designation: e.designationId ? (names.get(e.designationId) ?? null) : null,
        dateOfJoining: e.dateOfJoining ? ddmmyyyy(e.dateOfJoining) : null,
      },
    ]),
  );
}

/**
 * Year-to-date totals per employee and `category:code` from published payslips of the same
 * financial year (April–March) that start before `periodStart`.
 */
async function ytdBefore(employeeIds: string[], periodStart: Date) {
  const y = periodStart.getUTCFullYear();
  const fyStartYear = periodStart.getUTCMonth() >= 3 ? y : y - 1;
  const slips = await db().payslip.findMany({
    where: {
      employeeId: { in: employeeIds },
      status: 'PUBLISHED',
      periodStart: { gte: new Date(Date.UTC(fyStartYear, 3, 1)), lt: periodStart },
    },
    select: { runId: true, employeeId: true },
  });
  const out = new Map<string, Map<string, number>>();
  if (!slips.length) return out;
  const runEmployees = await db().payrollRunEmployee.findMany({
    where: { OR: slips.map((s) => ({ runId: s.runId, employeeId: s.employeeId })) },
    select: { id: true },
  });
  const items = await db().payrollItem.findMany({
    where: { runEmployeeId: { in: runEmployees.map((r) => r.id) } },
    select: { employeeId: true, category: true, code: true, amount: true },
  });
  for (const i of items) {
    const m = out.get(i.employeeId) ?? new Map<string, number>();
    const key = `${i.category}:${i.code}`;
    m.set(key, (m.get(key) ?? 0) + num(i.amount));
    out.set(i.employeeId, m);
  }
  return out;
}

const periodLabelOf = (d: Date) =>
  `${d.toLocaleString('en-US', { month: 'long', timeZone: 'UTC' })} ${d.getUTCFullYear()}`;

type PayrollRunRow = Prisma.PayrollRunGetPayload<object>;
type RunEmployeeRow = Prisma.PayrollRunEmployeeGetPayload<object>;

/**
 * Payslip template inputs for employees of a locked run. Amounts come from the frozen run
 * results (items / gross / deductions / net); nothing is recalculated.
 */
async function payslipInputBuilder(run: PayrollRunRow, employees: RunEmployeeRow[]) {
  const inst = await db().institution.findFirstOrThrow({ where: { id: run.institutionId } });
  const payments = await db().payrollPayment.findMany({ where: { runId: run.id } });
  const paymentByEmployee = new Map(payments.map((p) => [p.employeeId, p]));
  const departmentIds = employees.map((e) => e.departmentId).filter((d): d is string => !!d);
  const departments = await db().department.findMany({
    where: { id: { in: departmentIds } },
    select: { id: true, name: true },
  });
  const deptName = new Map(departments.map((d) => [d.id, d.name]));
  const periodLabel = periodLabelOf(run.periodStart);
  const profiles = await employeeProfiles(employees.map((e) => e.employeeId));
  const ytd = await ytdBefore(
    employees.map((e) => e.employeeId),
    run.periodStart,
  );
  const payDate = ddmmyyyy(run.finalizedAt ?? new Date());
  const build = async (re: RunEmployeeRow): Promise<PayslipInput> => {
    const items = await db().payrollItem.findMany({
      where: { runEmployeeId: re.id, showOnPayslip: true },
      orderBy: [{ displayOrder: 'asc' }, { code: 'asc' }],
    });
    const prior = ytd.get(re.employeeId);
    const rows = (cat: string[]) =>
      items
        .filter((i) => cat.includes(i.category) && num(i.amount) !== 0)
        .map((i) => [
          i.name,
          money(num(i.amount)),
          money(num(i.amount) + (prior?.get(`${i.category}:${i.code}`) ?? 0)),
        ]);
    const profile = profiles.get(re.employeeId);
    return {
      employeeName: re.employeeName,
      employeeCode: re.employeeCode,
      institution: inst.name,
      ...(re.departmentId && deptName.get(re.departmentId)
        ? { department: deptName.get(re.departmentId)! }
        : {}),
      periodLabel,
      periodStart: dateStr(run.periodStart),
      periodEnd: dateStr(run.periodEnd),
      revision: run.revision,
      calendarDays: String(num(re.calendarDays)),
      payableDays: String(num(re.payableDays)),
      lopDays: String(num(re.lopDays)),
      earnings: rows(['EARNING']),
      deductions: rows(['DEDUCTION']),
      employer: rows(['EMPLOYER_CONTRIBUTION']),
      gross: money(num(re.gross)),
      totalDeductions: money(num(re.deductions)),
      net: money(num(re.net)),
      ...(paymentByEmployee.get(re.employeeId)?.bankAccountMasked
        ? { bankAccount: paymentByEmployee.get(re.employeeId)!.bankAccountMasked! }
        : {}),
      ...(profile?.designation ? { designation: profile.designation } : {}),
      ...(profile?.dateOfJoining ? { dateOfJoining: profile.dateOfJoining } : {}),
      payDate,
      netInWords: rupeesInWords(num(re.net)),
    };
  };
  return { inst, periodLabel, build };
}

/** Queue job: render + store payslips for every computed employee of a FINALIZED run. */
export async function generatePayslipsJob(data: PayslipJob): Promise<void> {
  const run = await db().payrollRun.findFirst({ where: { id: data.runId } });
  if (!run || run.status !== 'FINALIZED') return;
  const [employees, existing] = await Promise.all([
    db().payrollRunEmployee.findMany({ where: { runId: run.id, status: 'OK' } }),
    db().payslip.findMany({ where: { runId: run.id }, select: { employeeId: true } }),
  ]);
  const done = new Set(existing.map((p) => p.employeeId));
  const { inst, periodLabel, build } = await payslipInputBuilder(run, employees);
  let published = 0;
  for (const re of employees) {
    if (done.has(re.employeeId)) continue;
    const input = await build(re);
    const rendered = await renderPdfTemplate(PAYSLIP_TEMPLATE, input, {
      groupId: inst.groupId,
      institutionId: inst.id,
      campusId: null,
      departmentId: re.departmentId,
    });
    const doc = await documentEngine.attach({
      ownerType: 'employee',
      ownerId: re.employeeId,
      module: 'payroll',
      metadata: {
        title: rendered.title,
        category: 'payroll',
        documentType: 'payslip',
        confidentiality: 'CONFIDENTIAL',
      },
      file: {
        fileName: `payslip-${dateStr(run.periodStart).slice(0, 7)}-${re.employeeCode}${run.revision > 1 ? `-r${run.revision}` : ''}.pdf`,
        mimeType: 'application/pdf',
        body: rendered.body,
      },
      extra: storedPdfMetadata(PAYSLIP_TEMPLATE, rendered, input, {
        runId: run.id,
        revision: run.revision,
      }),
      authorization: 'caller',
    });
    const slip = await db().payslip.create({
      data: withTenant({
        runId: run.id,
        employeeId: re.employeeId,
        institutionId: run.institutionId,
        periodStart: run.periodStart,
        periodEnd: run.periodEnd,
        revision: run.revision,
        documentId: doc.id,
        net: re.net,
      }),
    });
    published += 1;
    const employee = await db().employee.findFirst({
      where: { id: re.employeeId },
      select: { userId: true },
    });
    await notify(PAYROLL_NOTIFICATIONS.payslipPublished, [employee?.userId], {
      title: `Your payslip for ${periodLabel} is available`,
      body: `Net pay ${money(num(re.net))}.`,
      link: '/me/payslips',
      institutionId: run.institutionId,
    });
    await emit(
      PAYROLL_EVENTS.payslipPublished,
      {
        payslipId: slip.id,
        runId: run.id,
        employeeId: re.employeeId,
        periodStart: dateStr(run.periodStart),
        periodEnd: dateStr(run.periodEnd),
        revision: run.revision,
      },
      { institutionId: run.institutionId },
    );
  }
  await db().payrollRun.updateMany({
    where: { id: run.id, status: 'FINALIZED' },
    data: { payslipsPublishedAt: new Date() },
  });
  await audit.record({
    action: 'payroll.payslips.publish',
    entityType: 'payroll_run',
    entityId: run.id,
    metadata: { published },
  });
}

/* --------------------------------- PDF regeneration ------------------------------------- */

const REGENERATE_REASON = 'Regenerated with the current branding';

/**
 * Re-render a stored payslip PDF with the current branding as a NEW version of its document.
 * Uses the template input stored with the payslip; payslips stored before inputs were kept are
 * rebuilt from the frozen run results (amounts are never recalculated).
 */
async function regeneratePayslipDocument(slip: Prisma.PayslipGetPayload<object>) {
  if (!slip.documentId) throw new NotFoundError('Payslip');
  return regenerateStoredPdf(slip.documentId, {
    templateKey: PAYSLIP_TEMPLATE,
    authorization: 'caller',
    reason: REGENERATE_REASON,
    fallbackInput: async () => {
      const run = await db().payrollRun.findFirst({ where: { id: slip.runId } });
      const re = await db().payrollRunEmployee.findFirst({
        where: { runId: slip.runId, employeeId: slip.employeeId, status: 'OK' },
      });
      if (!run || !re) return null;
      return (await payslipInputBuilder(run, [re])).build(re);
    },
  });
}

/** Queue job: regenerate every stored payslip PDF of a run (e.g. after a logo change). */
export async function refreshPayslipPdfsJob(data: PayslipRefreshJob): Promise<void> {
  const slips = await db().payslip.findMany({
    where: { runId: data.runId, documentId: { not: null } },
    orderBy: { createdAt: 'asc' },
  });
  let regenerated = 0;
  const failed: string[] = [];
  for (const slip of slips) {
    try {
      await regeneratePayslipDocument(slip);
      regenerated += 1;
    } catch (err) {
      logger.warn({ err, payslipId: slip.id }, 'payroll: payslip PDF regeneration failed');
      failed.push(slip.id);
    }
  }
  await audit.record({
    action: 'payroll.payslips.regenerate_pdfs',
    entityType: 'payroll_run',
    entityId: data.runId,
    metadata: {
      regenerated,
      failed: failed.length,
      failedPayslipIds: failed.slice(0, 50),
      requestedByUserId: data.requestedByUserId,
    },
  });
}

/* --------------------------------- Payslip service -------------------------------------- */

async function payslipDtos(rows: Prisma.PayslipGetPayload<object>[]): Promise<PayslipDto[]> {
  const employees = await db().employee.findMany({
    where: { id: { in: [...new Set(rows.map((r) => r.employeeId))] } },
    select: { id: true, employeeCode: true, displayName: true },
  });
  const byId = new Map(employees.map((e) => [e.id, e]));
  return rows.map((r) => toPayslipDto(r, byId.get(r.employeeId)));
}

async function myEmployeeIds(): Promise<string[]> {
  const principal = currentPrincipal();
  if (!principal.userId) return [];
  return employeeIdsForUser(principal.userId);
}

export const payslipService = {
  async list(query: ListPayslipsQuery) {
    const ids = await institutionIdsFor('payroll.view');
    const where: Prisma.PayslipWhereInput = {
      ...institutionFilter(ids),
      ...(query.runId ? { runId: query.runId } : {}),
      ...(query.employeeId ? { employeeId: query.employeeId } : {}),
      ...(query.institutionId ? { institutionId: query.institutionId } : {}),
    };
    const [rows, total] = await Promise.all([
      db().payslip.findMany({
        where,
        orderBy: [{ periodStart: 'desc' }, { createdAt: 'desc' }],
        ...toPageWindow(query),
      }),
      db().payslip.count({ where }),
    ]);
    return toListResponse(await payslipDtos(rows), total, query);
  },

  /** Re-enqueue payslip generation for employees still missing one (idempotent). */
  async regenerate(runId: string) {
    const run = await loadRun(runId, 'payroll.view');
    await authorizeInstitution(run.institutionId, 'payroll.lock');
    if (run.status !== 'FINALIZED') {
      throw new AppError(409, 'INVALID_STATE', 'Payslips are generated for finalized runs only');
    }
    await enqueue<PayslipJob>(GENERATE_PAYSLIPS_JOB, {
      organizationId: currentOrganizationId(),
      runId,
    });
    return { queued: true };
  },

  /** Regenerate one stored payslip PDF with the current branding (new document version). */
  async regeneratePdf(id: string) {
    const slip = await db().payslip.findFirst({ where: { id } });
    if (!slip?.documentId || !hasPermission(currentPrincipal(), 'payroll.view')) {
      throw new NotFoundError('Payslip');
    }
    await assertInstitutionVisible(slip.institutionId, 'payroll.view', 'Payslip');
    await authorizeInstitution(slip.institutionId, 'payroll.lock');
    const { version } = await regeneratePayslipDocument(slip);
    await audit.record({
      action: 'payroll.payslip.regenerate_pdf',
      entityType: 'payslip',
      entityId: slip.id,
      metadata: { documentId: slip.documentId, versionNumber: version.versionNumber },
    });
    return {
      payslipId: slip.id,
      documentId: slip.documentId,
      versionNumber: version.versionNumber,
    };
  },

  /** Queue regeneration of every stored payslip PDF of a run (background job). */
  async regenerateRunPdfs(runId: string) {
    const run = await loadRun(runId, 'payroll.view');
    await authorizeInstitution(run.institutionId, 'payroll.lock');
    const count = await db().payslip.count({ where: { runId, documentId: { not: null } } });
    if (!count) {
      throw new AppError(409, 'INVALID_STATE', 'This run has no stored payslips to regenerate');
    }
    await enqueue<PayslipRefreshJob>(REFRESH_PAYSLIP_PDFS_JOB, {
      organizationId: currentOrganizationId(),
      runId,
      requestedByUserId: userId(),
    });
    await audit.record({
      action: 'payroll.payslips.regenerate_pdfs_request',
      entityType: 'payroll_run',
      entityId: runId,
      metadata: { payslips: count },
    });
    return { queued: true, payslips: count };
  },

  /** Employee self-service: own published payslips. */
  async mine(): Promise<PayslipDto[]> {
    if (!hasPermission(currentPrincipal(), 'payroll.view_own')) return [];
    const ids = await myEmployeeIds();
    if (!ids.length) return [];
    const rows = await db().payslip.findMany({
      where: { employeeId: { in: ids }, status: 'PUBLISHED' },
      orderBy: [{ periodStart: 'desc' }, { revision: 'desc' }],
    });
    return payslipDtos(rows);
  },

  /**
   * Signed download URL. Own payslips via self-access; anyone else needs payroll.view in the
   * payslip's institution AND document access (document engine rules). Others: 404.
   */
  async download(id: string) {
    const slip = await db().payslip.findFirst({ where: { id } });
    if (!slip?.documentId) throw new NotFoundError('Payslip');
    const own = (await myEmployeeIds()).includes(slip.employeeId);
    if (!own) {
      if (!hasPermission(currentPrincipal(), 'payroll.view')) throw new NotFoundError('Payslip');
      await assertInstitutionVisible(slip.institutionId, 'payroll.view', 'Payslip');
    } else if (!hasPermission(currentPrincipal(), 'payroll.view_own')) {
      throw new NotFoundError('Payslip');
    }
    await audit.record({
      action: 'payroll.payslip.download',
      entityType: 'payslip',
      entityId: id,
      metadata: { employeeId: slip.employeeId, self: own },
    });
    return documentEngine.downloadUrl(slip.documentId, { disposition: 'attachment' });
  },
};

