const FORM16_MAX_BYTES = 10 * 1024 * 1024;

async function form16Employee(employeeId: string) {
  const employee = await db().employee.findFirst({ where: { id: employeeId } });
  if (!employee) throw new InvalidReferenceError('employeeId', 'Employee');
  const assignment = await employeeAssignmentAsOf(employeeId, new Date());
  const institutionId = assignment?.institutionId ?? employee.institutionId;
  await authorizeInstitution(institutionId, 'form16.manage');
  return { employee, institutionId };
}

async function upsertForm16(
  employeeId: string,
  institutionId: string,
  financialYear: string,
  documentId: string,
) {
  const existing = await db().form16Record.findFirst({ where: { employeeId, financialYear } });
  const row = existing
    ? await db().form16Record.update({
        where: { id: existing.id },
        data: { documentId, status: 'DRAFT', publishedAt: null, publishedByUserId: null },
      })
    : await db().form16Record.create({
        data: withTenant({
          employeeId,
          institutionId,
          financialYear,
          documentId,
          uploadedByUserId: userId(),
        }),
      });
  await audit.record({
    action: existing ? 'payroll.form16.replace' : 'payroll.form16.create',
    entityType: 'form16_record',
    entityId: row.id,
    after: { employeeId, financialYear, documentId },
  });
  return row;
}

async function loadForm16(id: string) {
  const row = await db().form16Record.findFirst({ where: { id } });
  if (!row || !hasPermission(currentPrincipal(), 'form16.manage')) {
    throw new NotFoundError('Form 16');
  }
  await assertInstitutionVisible(row.institutionId, 'form16.manage', 'Form 16');
  return row;
}

/** Ids of documents generated from a PDF template (vs uploaded files). */
async function generatedDocumentIds(documentIds: string[]): Promise<Set<string>> {
  const docs = await db().document.findMany({
    where: { id: { in: documentIds } },
    select: { id: true, metadata: true },
  });
  return new Set(
    docs
      .filter(
        (d) => typeof (d.metadata as { templateKey?: unknown } | null)?.templateKey === 'string',
      )
      .map((d) => d.id),
  );
}

async function form16Dto(row: Prisma.Form16RecordGetPayload<object>) {
  const e = await db().employee.findFirst({
    where: { id: row.employeeId },
    select: { employeeCode: true },
  });
  const generated = await generatedDocumentIds([row.documentId]);
  return toForm16Dto(row, e, generated.has(row.documentId));
}

/** Form 16 summary input from FINALIZED payroll of the financial year (frozen run results). */
async function form16Input(
  employee: { id: string; displayName: string; employeeCode: string },
  institutionId: string,
  financialYear: string,
) {
  const fyStart = Number(financialYear.slice(0, 4));
  const from = strToDate(`${fyStart}-04-01`);
  const to = strToDate(`${fyStart + 1}-03-31`);
  const res = await db().payrollRunEmployee.findMany({
    where: { employeeId: employee.id, status: 'OK' },
  });
  const runs = await db().payrollRun.findMany({
    where: {
      id: { in: res.map((r) => r.runId) },
      status: 'FINALIZED',
      periodStart: { gte: from, lte: to },
    },
  });
  const runById = new Map(runs.map((r) => [r.id, r]));
  const tdsItems = await db().payrollItem.findMany({
    where: {
      runId: { in: runs.map((r) => r.id) },
      employeeId: employee.id,
      statutoryCode: 'TDS',
    },
  });
  const months = new Map<string, { gross: number; tds: number }>();
  for (const re of res) {
    const run = runById.get(re.runId);
    if (!run) continue;
    const key = dateStr(run.periodStart).slice(0, 7);
    const m = months.get(key) ?? { gross: 0, tds: 0 };
    m.gross += num(re.gross);
    m.tds += tdsItems.filter((i) => i.runId === re.runId).reduce((a, i) => a + num(i.amount), 0);
    months.set(key, m);
  }
  const totalGross = [...months.values()].reduce((a, m) => a + m.gross, 0);
  const totalTds = [...months.values()].reduce((a, m) => a + m.tds, 0);
  const inst = await db().institution.findFirstOrThrow({ where: { id: institutionId } });
  const input: Form16Input = {
    employeeName: employee.displayName,
    employeeCode: employee.employeeCode,
    institution: inst.name,
    financialYear,
    months: [...months.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([k, m]) => [k, money(m.gross), money(m.tds)]),
    gross: money(totalGross),
    tds: money(totalTds),
  };
  return { inst, input };
}

export const form16Service = {
  async list(query: ListForm16Query) {
    const ids = await institutionIdsFor('form16.manage');
    const where: Prisma.Form16RecordWhereInput = {
      ...institutionFilter(ids),
      ...(query.employeeId ? { employeeId: query.employeeId } : {}),
      ...(query.financialYear ? { financialYear: query.financialYear } : {}),
    };
    const [rows, total] = await Promise.all([
      db().form16Record.findMany({
        where,
        orderBy: [{ financialYear: 'desc' }, { createdAt: 'desc' }],
        ...toPageWindow(query),
      }),
      db().form16Record.count({ where }),
    ]);
    const employees = await db().employee.findMany({
      where: { id: { in: rows.map((r) => r.employeeId) } },
      select: { id: true, employeeCode: true },
    });
    const codes = new Map(employees.map((e) => [e.id, e]));
    const generated = await generatedDocumentIds(rows.map((r) => r.documentId));
    return toListResponse(
      rows.map((r) => toForm16Dto(r, codes.get(r.employeeId), generated.has(r.documentId))),
      total,
      query,
    );
  },

  /** Upload the certified Form 16 PDF (stored securely via the document engine). */
  async upload(fields: Form16FieldsInput, file: MultipartFile) {
    if (file.body.length > FORM16_MAX_BYTES) {
      throw new AppError(413, 'PAYLOAD_TOO_LARGE', 'Form 16 file is too large');
    }
    const { employee, institutionId } = await form16Employee(fields.employeeId);
    const doc = await documentEngine.attach({
      ownerType: 'employee',
      ownerId: employee.id,
      module: 'payroll',
      metadata: {
        title: `Form 16 FY ${fields.financialYear} - ${employee.displayName} (${employee.employeeCode})`,
        category: 'payroll',
        documentType: 'form16',
        confidentiality: 'CONFIDENTIAL',
      },
      file: { fileName: file.fileName, mimeType: file.mimeType, body: file.body },
      extra: { financialYear: fields.financialYear },
      authorization: 'caller',
    });
    return form16Dto(await upsertForm16(employee.id, institutionId, fields.financialYear, doc.id));
  },

  /** Placeholder generation from finalized payroll (gross + TDS per month of the FY). */
  async generate(fields: Form16FieldsInput) {
    const { employee, institutionId } = await form16Employee(fields.employeeId);
    const { inst, input } = await form16Input(employee, institutionId, fields.financialYear);
    const rendered = await renderPdfTemplate(FORM16_TEMPLATE, input, {
      groupId: inst.groupId,
      institutionId: inst.id,
      campusId: null,
      departmentId: null,
    });
    const doc = await documentEngine.attach({
      ownerType: 'employee',
      ownerId: employee.id,
      module: 'payroll',
      metadata: {
        title: rendered.title,
        category: 'payroll',
        documentType: 'form16',
        confidentiality: 'CONFIDENTIAL',
      },
      file: {
        fileName: `form16-${fields.financialYear}-${employee.employeeCode}.pdf`,
        mimeType: 'application/pdf',
        body: rendered.body,
      },
      extra: storedPdfMetadata(FORM16_TEMPLATE, rendered, input, {
        financialYear: fields.financialYear,
      }),
      authorization: 'caller',
    });
    return form16Dto(await upsertForm16(employee.id, institutionId, fields.financialYear, doc.id));
  },

  /**
   * Regenerate a GENERATED Form 16 summary PDF with the current branding (new document version;
   * the record keeps its status). Uploaded certified Form 16 files cannot be regenerated.
   */
  async regeneratePdf(id: string) {
    const row = await loadForm16(id);
    await authorizeInstitution(row.institutionId, 'form16.manage');
    const { version } = await regenerateStoredPdf(row.documentId, {
      authorization: 'caller',
      reason: REGENERATE_REASON,
      fallbackInput: async () => {
        const employee = await db().employee.findFirst({ where: { id: row.employeeId } });
        if (!employee) return null;
        return (await form16Input(employee, row.institutionId, row.financialYear)).input;
      },
    });
    await audit.record({
      action: 'payroll.form16.regenerate_pdf',
      entityType: 'form16_record',
      entityId: row.id,
      metadata: { documentId: row.documentId, versionNumber: version.versionNumber },
    });
    return form16Dto(await db().form16Record.findFirstOrThrow({ where: { id } }));
  },

  async publish(id: string) {
    const row = await loadForm16(id);
    await authorizeInstitution(row.institutionId, 'form16.manage');
    if (row.status === 'PUBLISHED') return form16Dto(row);
    const updated = await db().form16Record.update({
      where: { id },
      data: { status: 'PUBLISHED', publishedAt: new Date(), publishedByUserId: userId() },
    });
    await audit.record({
      action: 'payroll.form16.publish',
      entityType: 'form16_record',
      entityId: id,
      before: { status: row.status },
      after: { status: 'PUBLISHED' },
    });
    const employee = await db().employee.findFirst({
      where: { id: row.employeeId },
      select: { userId: true },
    });
    await notify(PAYROLL_NOTIFICATIONS.form16Published, [employee?.userId], {
      title: `Your Form 16 for FY ${row.financialYear} is available`,
      link: '/me/payslips',
      institutionId: row.institutionId,
    });
    return form16Dto(updated);
  },

  async mine() {
    if (!hasPermission(currentPrincipal(), 'payroll.view_own')) return [];
    const ids = await myEmployeeIds();
    if (!ids.length) return [];
    const rows = await db().form16Record.findMany({
      where: { employeeId: { in: ids }, status: 'PUBLISHED' },
      orderBy: { financialYear: 'desc' },
    });
    return Promise.all(rows.map(form16Dto));
  },

  async download(id: string) {
    const row = await db().form16Record.findFirst({ where: { id } });
    if (!row) throw new NotFoundError('Form 16');
    const own = (await myEmployeeIds()).includes(row.employeeId);
    if (own) {
      if (row.status !== 'PUBLISHED' || !hasPermission(currentPrincipal(), 'payroll.view_own')) {
        throw new NotFoundError('Form 16');
      }
    } else {
      await loadForm16(id);
    }
    await audit.record({
      action: 'payroll.form16.download',
      entityType: 'form16_record',
      entityId: id,
      metadata: { employeeId: row.employeeId, self: own },
    });
    return documentEngine.downloadUrl(row.documentId, { disposition: 'attachment' });
  },

  maxBytes: FORM16_MAX_BYTES,
};
