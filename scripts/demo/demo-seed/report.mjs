// Builds scripts/demo/demo-manifest.json and docs/DEMO_ACCOUNTS.md from the seeded contexts.
import fs from 'node:fs';
import path from 'node:path';
import { API_URL, DEMO_PASSWORD, ROOT, SUPERADMIN, SUPPORT, TODAY } from './lib.mjs';

const WEB_URL = process.env.WEB_URL ?? 'http://localhost:5180';

const enabledKeys = (states) => states.filter((f) => f.enabled).map((f) => f.key);

/** Organization block of the manifest (effective features per org + per institution). */
export async function describeOrg(ctx) {
  const orgFeatures = (await ctx.api('GET', '/features/effective')).data.features;
  const institutions = [];
  for (const inst of ctx.institutions) {
    const states = (await ctx.api('GET', `/features/effective?institutionId=${inst.id}`)).data
      .features;
    institutions.push({
      id: inst.id,
      name: inst.name,
      code: inst.code,
      type: inst.type,
      effectiveFeatures: enabledKeys(states),
    });
  }
  return {
    id: ctx.org.id,
    name: ctx.org.name,
    slug: ctx.slug,
    kind: ctx.meta.kind,
    plan: ctx.meta.plan,
    subscriptionStatus: ctx.meta.status,
    addOns: ctx.meta.addOns ?? [],
    overrides: ctx.overrides,
    licensedFeatures: orgFeatures.filter((f) => f.licensed).map((f) => f.key),
    effectiveFeatures: enabledKeys(orgFeatures),
    disabledFeatures: orgFeatures
      .filter((f) => !f.enabled)
      .map((f) => ({ key: f.key, reason: f.source })),
    caseNote: ctx.meta.caseNote ?? null,
    institutions,
  };
}

export function writeManifest({ orgs, users, checks }) {
  const manifest = {
    generatedAt: new Date().toISOString(),
    demoToday: TODAY,
    apiUrl: API_URL,
    webUrl: WEB_URL,
    password: DEMO_PASSWORD,
    organizations: orgs,
    users,
    licenceChecks: checks,
  };
  const file = path.join(ROOT, 'scripts/demo/demo-manifest.json');
  fs.writeFileSync(file, `${JSON.stringify(manifest, null, 2)}\n`);
  return file;
}

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');

export function writeAccountsDoc({ orgs, users, checks }) {
  const L = [];
  L.push('# Demo accounts');
  L.push('');
  L.push(
    '> Generated by `pnpm demo:seed` (`scripts/demo/seed-demo.mjs`). Do not edit by hand — re-run the seed instead.',
  );
  L.push('');
  L.push(`- Web app: ${WEB_URL}  ·  API: ${API_URL}`);
  L.push(`- **Password for every account: \`${DEMO_PASSWORD}\`**`);
  L.push(
    '- Machine-readable version (used by the end-to-end tests): [`scripts/demo/demo-manifest.json`](../scripts/demo/demo-manifest.json)',
  );
  L.push('');
  L.push('## Licence matrix');
  L.push('');
  L.push('| Organization | Slug | Kind | Plan | Status | Add-ons | Overrides | Enabled modules |');
  L.push('| --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const o of orgs) {
    const ov = o.overrides
      .map((x) => `${x.featureKey} ${x.enabled ? 'on' : 'off'} @ ${x.target}`)
      .join('; ');
    L.push(
      `| ${esc(o.name)} | \`${o.slug}\` | ${o.kind} | ${o.plan} | ${o.subscriptionStatus} | ${o.addOns.join(', ') || '—'} | ${esc(ov) || '—'} | ${o.effectiveFeatures.join(', ') || '_none_'} |`,
    );
  }
  L.push('');
  for (const o of orgs) {
    L.push(`### ${o.name} (\`${o.slug}\`)`);
    L.push('');
    if (o.caseNote) L.push(`${o.caseNote}`, '');
    L.push(
      `Not available: ${o.disabledFeatures.map((d) => `${d.key} (${d.reason})`).join(', ') || 'nothing'}.`,
    );
    L.push('');
    if (o.institutions.length) {
      L.push('| Institution | Code | Enabled modules |');
      L.push('| --- | --- | --- |');
      for (const i of o.institutions) {
        L.push(`| ${esc(i.name)} | ${i.code ?? ''} | ${i.effectiveFeatures.join(', ')} |`);
      }
      L.push('');
    }
  }
  L.push('## Accounts');
  L.push('');
  L.push('Platform administrators (sign in without choosing an organization):');
  L.push('');
  L.push('| Email | Role | What to try |');
  L.push('| --- | --- | --- |');
  L.push(
    `| \`${SUPERADMIN}\` | platform_super_admin | Organizations, plans, subscriptions, invoices, tenant access |`,
  );
  L.push(`| \`${SUPPORT}\` | platform_support_admin | Read-only support view of organizations |`);
  L.push('');
  for (const o of orgs) {
    const list = users.filter((u) => u.org === o.slug);
    if (!list.length) continue;
    L.push(`### ${o.name}`);
    L.push('');
    L.push('| Email | Role(s) | Scope | Linked record | Visible menu sections | Persona |');
    L.push('| --- | --- | --- | --- | --- | --- |');
    for (const u of list) {
      const roles = u.roles.map((r) => r.key).join(', ');
      const scopes = [...new Set(u.roles.map((r) => `${r.scope}: ${r.scopeName}`))].join('; ');
      const menus = Object.entries(u.menus ?? {})
        .map(([layout, items]) => `**${layout}**: ${items.map((m) => m.title).join(', ')}`)
        .join('<br>');
      L.push(
        `| \`${u.email}\` | ${roles} | ${esc(scopes)} | ${esc(u.linkedTo) || '—'} | ${menus || '_none_'} | ${esc(u.persona)} |`,
      );
    }
    L.push('');
  }
  L.push('## Licence enforcement spot-checks');
  L.push('');
  L.push('| Check | Request | Expected | Actual | Result |');
  L.push('| --- | --- | --- | --- | --- |');
  for (const c of checks) {
    L.push(
      `| ${esc(c.name)} | \`${c.as} ${c.method} ${c.path}\` | ${c.expected} | ${c.actual} | ${c.pass ? 'PASS' : 'FAIL'} |`,
    );
  }
  L.push('');
  const file = path.join(ROOT, 'docs/DEMO_ACCOUNTS.md');
  fs.writeFileSync(file, `${L.join('\n')}\n`);
  return file;
}
